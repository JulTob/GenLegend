def Title(hero):
	try: return hero.title
	except Exception as e: print(e)
	return "the adventurer"

def FullName(hero):
	try: return hero.name
	except Exception as e: print(e)
	return "our protagonist"

def Name(hero):
	try: return hero._name
	except Exception as e: print(e)
	return FullName(hero)

def Background(hero):
	try: return hero.background
	except Exception as e: print(e)
	return "adventurer"

def Species(hero):
	try: return hero.species
	except Exception as e: print(e)
	return "person"

def Race(hero):
	try: return Species(hero)
	except Exception as e: print(e)
	return "person"

def _guild_name(hero):
	return (
		getattr(
			hero,
			"char_class",
			None,
			)
		or "Adventurer"
		)


TOKEN = re.compile(r"{([a-zA-Z_][a-zA-Z0-9_]*)}")

def Story(hero):
	rng = hero.Dice_Bag(
		"identity.story",
		)

	result = Choice(
		[
			f'<h5 style = "font-size: 1.4em;">The story of {Title(hero)}</h5>',
			],
		rng=rng,
		)

	result += '<p style="font-size: 1.3em;">'
	result += Script(
		hero,
		rng=rng,
		)

	result += "</p>"
	return result


